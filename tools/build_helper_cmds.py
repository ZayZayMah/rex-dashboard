"""Packs the public command list + guides into src/helper_cmds.py (compact, no secrets). Run: python3 tools/build_helper_cmds.py"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
base = json.loads((root / "public/data/commands-baseline.json").read_text())
guides = json.loads((root / "public/data/guides.json").read_text())
rows = []
for c in base["commands"]:
    g = guides.get(c["name"]) or {}
    rows.append((c["name"], c["description"], c["access"], c.get("requires") or [],
                 [(p["name"], p["description"], bool(p["required"])) for p in c.get("params", [])],
                 g.get("summary", ""), g.get("details", ""), g.get("example", ""), g.get("tips") or []))
out = '"""Generated by tools/build_helper_cmds.py from the public commands list. Do not edit by hand."""\nCMDS = ' + repr(rows) + "\n"
(root / "src/helper_cmds.py").write_text(out)
print(len(rows), "commands packed")
